 25 import DORITO_PKG::*;
 26
 27  module DORITO_FSM
 28 (input  logic SYS_CLOCK,
 29 input  logic FSM_ARESET,
 30 input  logic [BUS_SIZE-1 : 0] IR_OUT,
 31 input  logic CARRYOUT, U_OVF, S_OVF, ALU_OUT_ZERO, ALU_OUT_POS, ALU_OUT_NEG,
 32
 33 output  logic SCLR_PC, INC_PC, LOAD_PC,
 34 output  logic LOAD_IR,
 35 output  logic [REG_ADDR_SIZE-1 : 0] SEL_SOURCE_REG1, SEL_SOURCE_REG2, SEL_DEST_REG,
 36 output  logic REG_FILE_ARESET, LOAD_DEST_REG,
 37 output  logic LOAD_ACCUM_REG,
 38 output  logic IMM_OFFSET_SELECTOR,
 39 output  logic SEL_SOURCE1, SEL_SOURCE2,
 40 output  logic [MNEMONIC_SIZE-1 : 0] ALU_CONTROL,
 41 output  logic SEL_DATA,
 42 output  logic SEL_ADDR, LOAD_ADDR_REG,
 43 output  logic MEM_ARESET, MEM_WRITE,
 44 output  logic EN        //ADDED
 45 );
 46
 47 //module DORITO_FSM (.*);
 48 //timeunit 1ns;
 49 //timeprecision 1ps;
 51 //VARIABLE DECLARATIONS FOR ALIASING (GIVING ALIAS TO DIFFERENT BU OR BUS SEGMENT)
 52  logic[3:0] INSTR_TYPE;
 53  logic[4:0] MNEMONIC;
 54  logic[2:0] RD_RS_MRI;
 55  logic[2:0] RS1_RB_MRI;
 56  logic[2:0] RS2_RI_MRI_RC_BRN;
 57  logic[1:0] CC_BRN;
 58
 59 //ASSIGNMENTS FOR ALIASING (GIVING ALIAS TO DIFFERENT BUS OR BUS SEGMENT)
 60 assign INSTR_TYPE = IR_OUT[31:28];
 61 assign MNEMONIC = IR_OUT[27:23];
 62 assign RD_RS_MRI = IR_OUT[22:20];
 63 assign RS1_RB_MRI = IR_OUT[19:17];
 64 assign RS2_RI_MRI_RC_BRN = IR_OUT[16:14];
 65 assign CC_BRN = IR_OUT[13:12];
 66
 67  logic [STATE_REG_WIDTH-1 : 0] P_STATE, N_STATE;
 68
 69 always_comb
 70 begin : FSM_NEXT_STATE_AND_OUTPUT_LOGIC
 71 N_STATE = 'x;
 72
 73 case (P_STATE)
 74 INIT /* 3'b000*/ :  N_STATE = FETCH;
 75
 76 FETCH /* 3'b001*/ :  N_STATE = EXEC_RG_IM_ADDR;
 77
 78 EXEC_RG_IM_ADDR /* 3'b010*/ :
 79
 80 case (INSTR_TYPE) //IR_OUT[31:28]     
 81 REG_REG /* 4'b0000*/ : N_STATE = FETCH;
 82
 83 REG_IMM  /* 4'b0001*/ : N_STATE = FETCH;
 84
 85 MRI_LOAD  /* 4'b0010*/ : N_STATE = EXEC_MRI_LOAD;
 86
 87 MRI_STORE  /* 4'b0011*/ : N_STATE = EXEC_MRI_STORE;
 88
 89 BRANCH   /* 4'b0100*/ :
 90
 91 if ((CC_BRN == 2'b00 && ALU_OUT_ZERO) || //BRANCH IF RC = 0
 92 (CC_BRN == 2'b01 && ALU_OUT_POS)  || //BRANCH IF RC IS +VE
 93 (CC_BRN == 2'b10 && ALU_OUT_NEG)  || //BRANCH IF RC IS -VE
 94 (CC_BRN == 2'b11) )     //BRANCH ALWAYS//
 95 N_STATE = EXEC_BRANCH;
 96 else N_STATE = FETCH;
 97 default : N_STATE = FETCH;
 98 endcase
 99
100 EXEC_MRI_LOAD /* 3'b011*/ : N_STATE = FETCH;
101
102 EXEC_MRI_STORE /* 3'b100*/ : N_STATE = FETCH;
103
104 EXEC_BRANCH  /*3'b101*/ : N_STATE = FETCH;
105
106 default : N_STATE = INIT;
107
108 endcase
109
110 SEL_SOURCE1 = '1; SEL_SOURCE2 = '0; SEL_DATA = '0; SEL_ADDR = '0;      
111 IMM_OFFSET_SELECTOR = '0;
112 SCLR_PC = '0; INC_PC = '0; LOAD_PC = '0; REG_FILE_ARESET = '0;
113 LOAD_IR = '0; LOAD_ADDR_REG = '0; LOAD_DEST_REG = '0; LOAD_ACCUM_REG = '0;
114 SEL_SOURCE_REG1 = '0; SEL_SOURCE_REG2 = '0; SEL_DEST_REG = '0;
115 ALU_CONTROL = '0;
116 MEM_WRITE = '0;
117 MEM_ARESET = '0;
118 EN = '0; //ADDED
119
120 case (P_STATE)
121
122 INIT /* 3'b000*/  :  begin
123 SCLR_PC = '1;
124 //SEL_ADDR = '0; //PASS PC_OUT TO MEM_ADDRESS
125 REG_FILE_ARESET = '1;
126 MEM_ARESET = '1;
127 end
128
129 FETCH /* 3'b001*/  :  begin
130 INC_PC = '1;
131 //SEL_ADDR = '0; //PASS PC_OUT TO MEM_ADDRESS
132 //SEL_DATA = '0; //PASS MEM_DATA_OUT TO INT_DATA_BUS
133 LOAD_IR = '1;
134
135 //ADDED
136         if (INSTR_TYPE==4'b0011)
137                 MEM_WRITE = '1;
138 end
141 EXEC_RG_IM_ADDR /* 3'b010*/  :                                                                                          142         case (INSTR_TYPE) //IR_OUT[31:28]
143
144         REG_REG /* 4'b0000*/  : begin
145         SEL_SOURCE_REG1 = RS1_RB_MRI; //IR_OUT[19:17];
146         //SEL_SOURCE1 = '1;     //PASS SOURCE_REG1 TO ALU_IN1
147
148         SEL_SOURCE_REG2 = RS2_RI_MRI_RC_BRN; //IR_OUT[16:14];
149         //SEL_SOURCE2 = '0; //PASS SOURCE_REG2 TO ALU_IN2
150
151         ALU_CONTROL = MNEMONIC; //IR_OUT[27:23];
152         SEL_DATA = '1; //PASS ALU_OUT   TO INT_DATA_BUS
153         SEL_DEST_REG =  RD_RS_MRI; //IR_OUT[22:20];
154         LOAD_DEST_REG = '1;
155         LOAD_ACCUM_REG = '1; //ADDED
156         end
157
158         REG_IMM /* 4'b0001*/  : begin
159         SEL_SOURCE_REG1 = RS1_RB_MRI; //IR_OUT[19:17];
160         //SEL_SOURCE1 = '1; //PASS SOURCE_REG1 TO ALU_IN1
161
162         IMM_OFFSET_SELECTOR = '1;  //change
163         //MAKE IMMEDIATE DATA 32BITS AND PASS IT TO MUX2
164         SEL_SOURCE2 = '1;
165
166         ALU_CONTROL = MNEMONIC; //IR_OUT[27:23];
167         SEL_DATA = '1; //PASS ALU_OUT TO INT_DATA_BUS
168         SEL_DEST_REG =  RD_RS_MRI; //IR_OUT[22:20];
169         LOAD_DEST_REG = '1;
170         LOAD_ACCUM_REG = '1; //ADDED
171         end
172
173
174         MRI_LOAD /* 4'b0010*/  : begin
175         SEL_SOURCE_REG1 = RS1_RB_MRI; //IR_OUT[19:17];
176         //SEL_SOURCE1 = '1; //PASS SOURCE_REG1 TO ALU_IN1
177
178         SEL_SOURCE_REG2 = RS2_RI_MRI_RC_BRN;  //IR_OUT[16:14];
179         //SEL_SOURCE2 = '0; //PASS SOURCE_REG2 TO ALU_IN2
180
181         ALU_CONTROL = ADD; //'0;//ADD (ADDING BASE AND INDEX ADDRESS)
182         LOAD_ADDR_REG = '1;
183         LOAD_ACCUM_REG = '1; //ADDED
184         end
185
186         MRI_STORE /* 4'b0011*/  : begin
187         SEL_SOURCE_REG1 = RS1_RB_MRI; //IR_OUT[19:17];
188         //SEL_SOURCE1 = '1; //PASS SOURCE_REG1 TO ALU_IN1
189
190         SEL_SOURCE_REG2 = RS2_RI_MRI_RC_BRN; //IR_OUT[16:14];
191         //SEL_SOURCE2 = '0; //PASS SOURCE_REG2 TO ALU_IN2
192
193         ALU_CONTROL = ADD; //'0; //ADD (ADDING BASE AND INDEX ADDRESS)
194         LOAD_ADDR_REG = '1;
195         LOAD_ACCUM_REG = '1; //ADDED
196         MEM_WRITE = '1; //ADDED FOR TEST
197         //SEL_ADDR = '1; //ADDED FOR TEST
198         end
199
200         BRANCH   /* 4'b0100*/ : begin    
201         SEL_SOURCE_REG2 = RS2_RI_MRI_RC_BRN;  //IR_OUT[16:14];
202         //SEL_SOURCE2 = '0; //PASS SOURCE_REG2  TO ALU_IN2
203         //IN THIS CASE, SOURCE_REG2 IS EVALUATION REFISTER FOR BRANCH OPERATION
204         ALU_CONTROL = PASS_IN2; //5'b00101; //PASS ALU_IN2 TO ALU_OUT
205         //NOW ALU_OUT_POS, ALU_OUT_POS AND ALU_OUT_NEG FLAG VALUES
206         //WILL BE AVAILABLE FOR EVALUATION REGISTER
207         end
208
209         default : ;
210         endcase
211
212 EXEC_MRI_LOAD /* 3'b011*/  : begin
213 SEL_ADDR = '1; //PASS ADDR_REG_OUT TO MEM_ADDRESS
214 EN = '1; //ADDED
215
216 //SEL_DATA = '0; //PASS MEM_DATA_OUT TO INT_DATA_BUS
217 SEL_DEST_REG =  RD_RS_MRI;
218 LOAD_DEST_REG = '1; //IR_OUT[22:20];
219 LOAD_ACCUM_REG = '1; //ADDED
220 end
221
222 EXEC_MRI_STORE /* 3'b100*/  : begin
223 //SEL_SOURCE2 = '0; //PASS SOURCE_REG2 TO ALU_IN2
224 //SEL_SOURCE_REG2 = RS2_RI_MRI_RC_BRN;//ADDED
225 SEL_SOURCE_REG2 = RD_RS_MRI;//CHANGED
226 ALU_CONTROL = PASS_IN2;//5'b00101; //PASS ALU_IN2 TO MEM_DATA_IN
227 EN = '1; //ADDED
228 LOAD_ACCUM_REG = '1; //ADDED
229
230 SEL_ADDR = '1; //PASS ADDR_REG_OUT TO MEM_ADDRESS 
231 MEM_WRITE = '1; //WRITE TO MEMORY
232 end
233
234
235 EXEC_BRANCH /*3'b101*/ :        begin
236 SEL_SOURCE1 = '0; //PASS PC_OUT TO ALU_IN1
237
238 //IMM_OFFSET_SELECTOR = '1;
239 IMM_OFFSET_SELECTOR = '1; //CHANGE
240 //MAKE PC_OFFSET 32-BIT AND SIGN EXTENDED AND PASS IT TO MUX2
241 SEL_SOURCE2 = '1; //PASS OFFSET TO ALU_IN2
242
243 ALU_CONTROL = ADD;//ADD; //ADD (ADD OFFSET TO PC)
244 LOAD_ACCUM_REG = '1; //ADDED
245 SEL_DATA = '1; //PASS ALU_OUT   TO INT_DATA_BUS
246 LOAD_PC = '1;  //CHANGE PC AS REQUIRE BY BRANCH INSTRUCTIONS
247 end
248
249 default : ;
250
251 endcase
252
253 end : FSM_NEXT_STATE_AND_OUTPUT_LOGIC
254
255
256 always_ff @ (posedge SYS_CLOCK, posedge FSM_ARESET)
257 begin : FSM_PRESENT_STATE_REG
258
259 if (FSM_ARESET)
260 P_STATE <= '0;
261 else
262 P_STATE <= N_STATE;
263
264 end : FSM_PRESENT_STATE_REG
265
266 endmodule : DORITO_FSM  
